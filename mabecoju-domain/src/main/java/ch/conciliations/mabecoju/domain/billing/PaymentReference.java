package ch.conciliations.mabecoju.domain.billing;

import ch.conciliations.mabecoju.domain.shared.DomainException;
import ch.conciliations.mabecoju.domain.shared.ErrorCode;

import java.math.BigInteger;
import java.util.Locale;
import java.util.Optional;

/**
 * Swiss payment references printed on QR-bills, so that incoming payments can be matched to their debtor.
 * <ul>
 *     <li>QR reference: 26 digits plus a modulo 10 recursive check digit; requires a QR-IBAN.</li>
 *     <li>Creditor reference (ISO 11649): {@code RF}, two check digits and up to 21 characters; for a plain IBAN.</li>
 * </ul>
 */
public final class PaymentReference {

    /** How references are formed, depending on the creditor account. */
    public enum Style { NONE, QR_REFERENCE, CREDITOR_REFERENCE }

    /** Kind of document a reference is generated for, first digit of the payload. */
    public enum DocumentKind {
        INVOICE(1), ADVANCE_REQUEST(2);

        private final int digit;

        DocumentKind(int digit) {
            this.digit = digit;
        }
    }

    private static final int[] MOD10_TABLE = {0, 9, 4, 6, 8, 2, 7, 1, 3, 5};

    private PaymentReference() {
    }

    /**
     * Deterministic payload for a document and a customer: kind (1 digit), document id (9) and customer id (9).
     * The same document and customer always get the same reference, on reminders too.
     */
    public static String payload(DocumentKind kind, long documentId, long customerId) {
        if (documentId > 999_999_999L || customerId > 999_999_999L) {
            throw new DomainException(ErrorCode.PAYMENT_REFERENCE_INVALID, "Identifier too large for a payment reference");
        }
        return String.format(Locale.ROOT, "%d%09d%09d", kind.digit, documentId, customerId);
    }

    public static String create(Style style, String payload) {
        return switch (style) {
            case QR_REFERENCE -> qrReference(payload);
            case CREDITOR_REFERENCE -> creditorReference(payload);
            case NONE -> throw new DomainException(ErrorCode.NO_CREDITOR_ACCOUNT, "No payment reference without a creditor account");
        };
    }

    /** Pads the digits to 26 and appends the modulo 10 recursive check digit. */
    public static String qrReference(String digits) {
        if (!digits.matches("\\d{1,26}")) {
            throw new DomainException(ErrorCode.PAYMENT_REFERENCE_INVALID, "A QR reference is made of 1 to 26 digits");
        }
        String padded = "0".repeat(26 - digits.length()) + digits;
        return padded + mod10Recursive(padded);
    }

    /** {@code RF} + ISO 7064 MOD 97-10 check digits + payload. */
    public static String creditorReference(String payload) {
        String cleaned = payload.replace(" ", "").toUpperCase(Locale.ROOT);
        if (!cleaned.matches("[0-9A-Z]{1,21}")) {
            throw new DomainException(ErrorCode.PAYMENT_REFERENCE_INVALID, "A creditor reference payload is made of 1 to 21 letters or digits");
        }
        int check = 98 - mod97(cleaned + "RF00");
        return "RF" + (check < 10 ? "0" : "") + check + cleaned;
    }

    /** Document and customer a reference was generated for (see {@link #payload}). */
    public record Decoded(DocumentKind kind, long documentId, long customerId) {
    }

    /**
     * Reads back the document and the customer of a QR or creditor reference generated by this application.
     * Empty for an invalid reference or one made elsewhere (another creditor, the legacy application).
     */
    public static Optional<Decoded> decode(String reference) {
        if (reference == null) {
            return Optional.empty();
        }
        String cleaned = reference.replace(" ", "").toUpperCase(Locale.ROOT);
        String payload;
        if (isValidQrReference(cleaned)) {
            String digits = cleaned.substring(0, 26);
            if (!digits.startsWith("0000000")) {
                return Optional.empty();
            }
            payload = digits.substring(7);
        } else if (isValidCreditorReference(cleaned)) {
            payload = cleaned.substring(4);
        } else {
            return Optional.empty();
        }
        if (!payload.matches("[12]\\d{18}")) {
            return Optional.empty();
        }
        DocumentKind kind = payload.charAt(0) == '1' ? DocumentKind.INVOICE : DocumentKind.ADVANCE_REQUEST;
        return Optional.of(new Decoded(kind, Long.parseLong(payload.substring(1, 10)), Long.parseLong(payload.substring(10))));
    }

    public static boolean isValidQrReference(String reference) {
        String digits = reference.replace(" ", "");
        return digits.matches("\\d{27}") && mod10Recursive(digits.substring(0, 26)) == digits.charAt(26) - '0';
    }

    public static boolean isValidCreditorReference(String reference) {
        String cleaned = reference.replace(" ", "").toUpperCase(Locale.ROOT);
        return cleaned.matches("RF\\d{2}[0-9A-Z]{1,21}") && mod97(cleaned.substring(4) + cleaned.substring(0, 4)) == 1;
    }

    /** A QR-IBAN has an institution id (positions 5 to 9) between 30000 and 31999. */
    public static boolean isQrIban(String iban) {
        String cleaned = iban == null ? "" : iban.replace(" ", "").toUpperCase(Locale.ROOT);
        if (!cleaned.matches("(CH|LI)\\d{7}.*")) {
            return false;
        }
        int iid = Integer.parseInt(cleaned.substring(4, 9));
        return iid >= 30000 && iid <= 31999;
    }

    public static Style styleFor(String iban) {
        if (iban == null || iban.isBlank()) {
            return Style.NONE;
        }
        return isQrIban(iban) ? Style.QR_REFERENCE : Style.CREDITOR_REFERENCE;
    }

    private static int mod10Recursive(String digits) {
        int carry = 0;
        for (char c : digits.toCharArray()) {
            carry = MOD10_TABLE[(carry + c - '0') % 10];
        }
        return (10 - carry) % 10;
    }

    private static int mod97(String text) {
        StringBuilder numeric = new StringBuilder();
        for (char c : text.toCharArray()) {
            numeric.append(Character.isDigit(c) ? String.valueOf(c) : String.valueOf(c - 'A' + 10));
        }
        return new BigInteger(numeric.toString()).mod(BigInteger.valueOf(97)).intValue();
    }
}
